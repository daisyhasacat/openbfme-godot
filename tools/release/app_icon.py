#!/usr/bin/env python3
"""Lane OWNERFIX-3: the OpenBFME application icon (the ring), for the game and the launcher, on every platform.

The source is godot/assets/app_icon/openbfme.ico (PNG frames 16, 32, 48, 64, 128, 256, the project's own artwork; pinned in public_binaries.txt). From it:
  godot/assets/app_icon/openbfme.icns      the macOS bundle icon (export preset "macOS Universal": application/icon)
  launcher/assets/app_icon/openbfme.ico    the launcher's copy (its Windows preset: application/icon; a project only reads its own res://)
  launcher/assets/app_icon/openbfme.icns
  godot/scripts/app_icon.gd                the window icon at run time (DisplayServer.set_icon): the 256 PNG as base64 text, because the
  launcher/scripts/ui/app_icon.gd          release packs hold only text resources and scenes (tools/release/audit_package.py PCK_RULES)

  python3 tools/release/app_icon.py              write the generated files
  python3 tools/release/app_icon.py --check      fail when a generated file differs from what the source gives
  python3 tools/release/app_icon.py --check-exe <exe>...   fail unless each Windows executable's icon group is exactly the source's frames
"""
import base64
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "godot/assets/app_icon/openbfme.ico"
# exactly the six sizes of Godot's own icon: the Windows export's TemplateModifier (application/modify_resources) rewrites the template's six
# icon resources in place, and an .ico with another set of frames is silently ignored (the 7-frame .ico with a 24 x 24 frame left Godot's icon)
SIZES = (16, 32, 48, 64, 128, 256)
# ICNS element types holding PNG data, by edge (Apple's icns format: icp4 16, icp5 32, icp6 64, ic07 128, ic08 256)
ICNS_TYPES = {16: b"icp4", 32: b"icp5", 64: b"icp6", 128: b"ic07", 256: b"ic08"}
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"


def read_ico(data: bytes) -> dict[int, bytes]:
    """{edge: PNG bytes} of an ICO made of square PNG frames; ValueError for anything else"""
    if len(data) < 6:
        raise ValueError("truncated ICO header")
    reserved, kind, count = struct.unpack_from("<HHH", data, 0)
    if reserved != 0 or kind != 1 or count == 0:
        raise ValueError("not an icon file")
    if len(data) < 6 + 16 * count:
        raise ValueError("truncated ICO directory")
    frames = {}
    for i in range(count):
        w, h, _, _, _, _, size, offset = struct.unpack_from("<BBBBHHII", data, 6 + 16 * i)
        w, h = w or 256, h or 256
        if offset + size > len(data):
            raise ValueError(f"frame {i} runs past the end")
        png = data[offset:offset + size]
        if not png.startswith(PNG_MAGIC):
            raise ValueError(f"frame {i} ({w}x{h}) is not PNG data")
        pw, ph = struct.unpack_from(">II", png, 16)
        if (pw, ph) != (w, h) or w != h:
            raise ValueError(f"frame {i}: directory says {w}x{h}, the PNG is {pw}x{ph}")
        if w in frames:
            raise ValueError(f"two {w}x{w} frames")
        frames[w] = png
    if tuple(sorted(frames)) != SIZES:
        raise ValueError(f"frames {sorted(frames)}, expected {list(SIZES)}")
    return frames


def make_icns(frames: dict[int, bytes]) -> bytes:
    body = b"".join(t + struct.pack(">I", 8 + len(frames[e])) + frames[e] for e, t in sorted(ICNS_TYPES.items()))
    return b"icns" + struct.pack(">I", 8 + len(body)) + body


def make_gd(png: bytes, where: str) -> str:
    b64 = base64.b64encode(png).decode("ascii")
    lines = [b64[i:i + 120] for i in range(0, len(b64), 120)]
    return (
        f"## Lane OWNERFIX-3: the OpenBFME icon (the ring) as the window / taskbar / dock icon of {where}, set at start (DisplayServer.set_icon).\n"
        "## GENERATED by tools/release/app_icon.py from godot/assets/app_icon/openbfme.ico (its 256 x 256 frame): do not edit.\n"
        "## The PNG is base64 text: the release packs hold text resources only (tools/release/audit_package.py PCK_RULES).\n"
        "extends RefCounted\n\n"
        "const SIZE := 256\n"
        "const PNG_BASE64 := (\"\"\n" + "".join(f'\t+ "{l}"\n' for l in lines) + ")\n\n\n"
        "## the icon's image; null when the text does not decode to the 256 x 256 PNG (a damaged script)\n"
        "static func image() -> Image:\n"
        "\tvar img := Image.new()\n"
        "\tif img.load_png_from_buffer(Marshalls.base64_to_raw(PNG_BASE64)) != OK or img.get_width() != SIZE or img.get_height() != SIZE:\n"
        "\t\treturn null\n"
        "\treturn img\n\n\n"
        "## sets the window icon; \"\" when done, else why not (the caller reports it). A headless run has no window: nothing to set\n"
        "static func apply() -> String:\n"
        "\tif DisplayServer.get_name() == \"headless\":\n"
        "\t\treturn \"\"\n"
        "\tvar img := image()\n"
        "\tif img == null:\n"
        "\t\treturn \"app_icon.gd: the icon does not decode\"\n"
        "\tDisplayServer.set_icon(img)\n"
        "\treturn \"\"\n"
    )


def outputs() -> dict[Path, bytes]:
    data = SOURCE.read_bytes()
    frames = read_ico(data)
    icns = make_icns(frames)
    return {
        REPO / "godot/assets/app_icon/openbfme.icns": icns,
        REPO / "launcher/assets/app_icon/openbfme.ico": data,
        REPO / "launcher/assets/app_icon/openbfme.icns": icns,
        REPO / "godot/scripts/app_icon.gd": make_gd(frames[256], "the game").encode("utf-8"),
        REPO / "launcher/scripts/ui/app_icon.gd": make_gd(frames[256], "the launcher").encode("utf-8"),
    }


def exe_icon_frames(exe: bytes) -> list[bytes]:
    """the PNG frames of the first RT_GROUP_ICON of a PE file, in its directory order"""
    import pefile  # dev tooling: present on the build hosts
    pe = pefile.PE(data=exe)
    icons, groups = {}, []
    for t in getattr(pe, "DIRECTORY_ENTRY_RESOURCE", None).entries if hasattr(pe, "DIRECTORY_ENTRY_RESOURCE") else []:
        for e in t.directory.entries:
            for lang in e.directory.entries:
                blob = pe.get_data(lang.data.struct.OffsetToData, lang.data.struct.Size)
                if t.id == 3:
                    icons[e.id] = blob
                elif t.id == 14:
                    groups.append(blob)
    if not groups:
        raise ValueError("no icon group (RT_GROUP_ICON)")
    g = groups[0]
    _, _, count = struct.unpack_from("<HHH", g, 0)
    out = []
    for i in range(count):
        ident = struct.unpack_from("<H", g, 6 + 14 * i + 12)[0]
        if ident not in icons:
            raise ValueError(f"the group names icon {ident}, which the file has not got")
        out.append(icons[ident])
    return out


def check_exe(path: Path) -> list[str]:
    want = sorted(read_ico(SOURCE.read_bytes()).values())
    try:
        got = sorted(exe_icon_frames(path.read_bytes()))
    except Exception as e:  # pefile's PEFormatError, a short read, a missing directory: never a pass
        return [f"{path}: {e}"]
    return [] if got == want else [f"{path}: its icon is not the OpenBFME icon ({len(got)} frames, none or not all of openbfme.ico's)"]


def main(argv: list[str]) -> int:
    if argv[1:2] == ["--check-exe"]:
        if len(argv) < 3:
            print("app_icon.py --check-exe: no executable given")
            return 2
        problems = [p for a in argv[2:] for p in check_exe(Path(a))]
        for p in problems:
            print("APP ICON FAIL:", p)
        if not problems:
            print(f"app icon ok: {len(argv) - 2} executable(s)")
        return 1 if problems else 0
    check = argv[1:2] == ["--check"]
    bad = []
    for path, data in outputs().items():
        if check:
            if not path.exists() or path.read_bytes() != data:
                bad.append(str(path.relative_to(REPO)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if bad:
        print("APP ICON FAIL: not what tools/release/app_icon.py generates (run it):", ", ".join(bad))
        return 1
    print("app icon " + ("files match the source" if check else "files written"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
